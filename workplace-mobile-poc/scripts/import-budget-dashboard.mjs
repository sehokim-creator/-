/*
 * Extracts the 예산관리 대시보드 export into app/budget-actuals.ts.
 *
 *   node scripts/import-budget-dashboard.mjs <dashboard.html> [outPath]
 *
 * The dashboard is a self-contained Chart.js page that carries its figures in
 * three `const` literals — RAW_DATA (budget codes), TX_DATA (transactions) and
 * CONTRACT_DATA (품의 links per code). This reads those literals rather than
 * scraping the rendered DOM, so a later monthly export drops straight in:
 * re-run the script and the screen picks up the new month.
 *
 * The as-of month is derived from the newest transaction date, not from the
 * filename — the filename said 2026_6 but that is a label, and pacing maths is
 * wrong if the closed-month count is wrong.
 *
 * NOTE: the output holds real figures, vendor names and internal 품의 URLs. It
 * belongs in a private repository only.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [, , input, output = "app/budget-actuals.ts"] = process.argv;
if (!input) {
  console.error("usage: node scripts/import-budget-dashboard.mjs <dashboard.html> [outPath]");
  process.exit(1);
}

const src = readFileSync(resolve(input), "utf8");

function literal(name) {
  const match = src.match(new RegExp(`^const ${name}\\s*=\\s*(\\[[\\s\\S]*?\\]|\\{[\\s\\S]*?\\});\\s*$`, "m"));
  if (!match) throw new Error(`${name} not found — did the dashboard's export format change?`);
  return JSON.parse(match[1]);
}

const lines = literal("RAW_DATA");
const transactions = literal("TX_DATA");
const contracts = literal("CONTRACT_DATA");

const dates = transactions.map((tx) => tx.date).filter(Boolean).sort();
const asOf = dates[dates.length - 1];
const closedMonths = Number(asOf.slice(5, 7));

// Monthly actuals, zero-filled so a month with no spend still occupies its slot
// on the trend instead of collapsing the axis.
const byMonth = new Map();
for (const tx of transactions) {
  const key = tx.date.slice(0, 7);
  byMonth.set(key, (byMonth.get(key) ?? 0) + tx.amount);
}
const year = asOf.slice(0, 4);
const monthly = Array.from({ length: closedMonths }, (_, i) => {
  const key = `${year}-${String(i + 1).padStart(2, "0")}`;
  return { month: key, amount: byMonth.get(key) ?? 0 };
});

const sum = (rows, field) => rows.reduce((total, row) => total + (row[field] ?? 0), 0);
const budget = sum(lines, "budget");
const used = sum(lines, "used");

const json = (value) => JSON.stringify(value, null, 1);

const banner = `/*
 * 예산관리 대시보드 ${asOf} 스냅샷 — 실제 데이터입니다.
 *
 * Generated by scripts/import-budget-dashboard.mjs. Do not hand-edit: re-run the
 * script against the next monthly export instead.
 *
 * 실제 금액·거래처·내부 품의 링크가 들어 있습니다. 비공개 저장소 밖으로 내보내지
 * 마세요. 운영 연동은 이 스냅샷이 아니라 lib/sheets-source.ts의 'budget-lines'
 * 바인딩(세부내역 시트)을 씁니다.
 *
 * 요약: 예산 ${(budget / 1e8).toFixed(2)}억 · 집행 ${(used / 1e8).toFixed(2)}억 (${((used / budget) * 100).toFixed(1)}%)
 *      항목 ${lines.length}건 · 거래 ${transactions.length}건 · ${closedMonths}개월 마감
 */

export type BudgetLine = {
  code: string;
  type: "Opex" | "Capex";
  acct: string;
  name: string;
  budget: number;
  used: number;
  pct: number;
  remain: number;
};

export type BudgetTransaction = {
  code: string;
  date: string;
  name: string;
  desc: string;
  owner: string;
  amount: number;
};

export type BudgetApproval = { name: string; url: string; category: string };

/** 스냅샷 기준일과 마감 개월 수. 페이싱·착지 전망이 이 값을 기준으로 계산됩니다. */
export const budgetAsOf = ${JSON.stringify(asOf)};
export const budgetClosedMonths = ${closedMonths};
export const budgetFiscalMonths = 12;

/** 월별 집행액. 집행이 없는 달도 0으로 채워 축이 접히지 않게 합니다. */
export const budgetMonthly: Array<{ month: string; amount: number }> = ${json(monthly)};

export const budgetLines: BudgetLine[] = ${json(lines)};

export const budgetTransactions: BudgetTransaction[] = ${json(transactions)};

/** 예산코드별 품의·계약 링크 (사내망에서만 열립니다). */
export const budgetApprovals: Record<string, BudgetApproval[]> = ${json(contracts)};
`;

writeFileSync(resolve(output), banner);

console.log(`${output}`);
console.log(`  as of ${asOf} · ${closedMonths} closed months`);
console.log(`  budget ${(budget / 1e8).toFixed(2)}억 · used ${(used / 1e8).toFixed(2)}억 (${((used / budget) * 100).toFixed(1)}%)`);
console.log(`  ${lines.length} lines · ${transactions.length} transactions · ${Object.keys(contracts).length} codes with 품의 links`);
console.log(`  monthly: ${monthly.map((m) => `${m.month.slice(5)}:${(m.amount / 1e8).toFixed(2)}억`).join(" ")}`);
